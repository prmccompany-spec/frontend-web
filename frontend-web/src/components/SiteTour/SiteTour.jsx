const DEFAULT_ICON = 'compass';

function TourCard({ backProps, closeProps, index, isLastStep, primaryProps, size, skipProps, step, tooltipProps }) {
  const pct = Math.round(((index + 1) / size) * 100);

  return (
    <div className="tour-card" {...tooltipProps}>
      <div className="tour-card-header">
        <span className="tour-card-icon">{ICONS[step.icon] ?? ICONS[DEFAULT_ICON]}</span>
        <span className="tour-card-step">Step {index + 1} of {size}</span>
        <button className="tour-card-close" {...closeProps} aria-label="Close tour">
          <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.5" strokeLinecap="round" strokeLinejoin="round">
            <line x1="18" y1="6" x2="6" y2="18" /><line x1="6" y1="6" x2="18" y2="18" />
          </svg>
        </button>
      </div>

      <div className="tour-card-progress">
        <div className="tour-card-progress-fill" style={{ width: `${pct}%` }} />
      </div>

      <div className="tour-card-body">
        {step.title && <h3 className="tour-card-title">{step.title}</h3>}
        <p className="tour-card-content">{step.content}</p>
      </div>

      <div className="tour-card-footer">
        <button className="tour-card-skip" {...skipProps}>Skip Tour</button>
        <div className="tour-card-nav">
          {index > 0 && <button className="tour-card-back" {...backProps}>Back</button>}
          <button className="tour-card-next" {...primaryProps}>{isLastStep ? 'Finish' : 'Next'}</button>
        </div>
      </div>
    </div>
  );
}

function SiteTour({ tourKey, steps, run, restartToken = 0, onClose }) {
  const handleCallback = (data) => {
    const { status } = data;
    if (status === STATUS.FINISHED || status === STATUS.SKIPPED) {
      onClose?.();
    }
  };

  return (
    <Joyride
      // Remounting on restartToken change resets Joyride's internal step
      // index, so replaying the tour always starts from step 1.
      key={`${tourKey}-${restartToken}`}
      steps={steps}
      run={run}
      continuous
      disableOverlayClose
      scrollToFirstStep
      tooltipComponent={TourCard}
      callback={handleCallback}
      styles={{
        options: {
          primaryColor: '#7c3aed',
          zIndex: 10050,
          overlayColor: 'rgba(20, 12, 40, 0.55)',
        },
        spotlight: {
          borderRadius: 10,
          boxShadow: '0 0 0 4px rgba(139, 92, 246, 0.55)',
        },
      }}
    />
  );
}

export default SiteTour;
